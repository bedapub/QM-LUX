"""3-D conformer generation and SDF file writing for XTB/CREST pre-optimisation.

The Snakemake workflow calls :func:`generate_conf_xtb` to generate one SDF file
per compound under ``<folder>/0/<index>/<name>.sdf``.  Conformers are embedded
with ETKDGv2, force-field-optimised with MMFF94s, sorted by energy, and written
so that XTB reads the lowest-energy conformer first.

Functions originally in :mod:`qm_lux.sdf_generator` are re-exported from that
module for backward compatibility.
"""

import os
import pickle
import shutil

from rdkit import Chem
from rdkit.Chem import AllChem, SaltRemover, rdDistGeom


def generate_conf_xtb(folder):
    """Generate MMFF94s-optimised conformers and write SDF files for XTB.

    Reads compound data from ``<folder>/xtb_input.pkl`` and calls
    :func:`sdf_run` to embed, optimise, and write conformers.

    Parameters
    ----------
    folder : str
        Working directory containing ``xtb_input.pkl``.
    """
    with open(os.path.join(folder, "xtb_input.pkl"), "rb") as f:
        smiles_test = pickle.load(f)

    sub_folder = 0
    nconfs = 10
    rmsthresh = 0.1
    sdf_run(folder, list(smiles_test["SRN"]), "SMILES_CLEAN", smiles_test, rmsthresh, nconfs, sub_folder, "OVERWRITE")


def get_info_mol(df, folder_mol, nconfs, SMILES):
    """Extract SMILES, output path, and molecule name from a single-row DataFrame.

    Parameters
    ----------
    df : pandas.Series or single-row pandas.DataFrame
        Row containing ``SRN`` and the SMILES column.
    folder_mol : str
        Output directory path (used as the base for SDF output paths).
    nconfs : int
        Number of conformers requested (printed for logging).
    SMILES : str
        SMILES column name.

    Returns
    -------
    tuple
        ``(smiles, output_path, mol_name)``
    """
    smiles = df[SMILES]
    mol_name = df["SRN"]
    print(mol_name)
    print(smiles)
    print("Number of conformers generated by user:", nconfs)
    output_pat = folder_mol
    return smiles, output_pat, mol_name


def get_conf_MMFF_opt(smiles, rmsthresh, nconfs):
    """Embed and MMFF94s-optimise multiple conformers for a SMILES string.

    Parameters
    ----------
    smiles : str
        Input SMILES string.
    rmsthresh : float
        RMSD pruning threshold used by ETKDGv2 to remove similar conformers.
    nconfs : int
        Maximum number of conformers to embed.

    Returns
    -------
    tuple
        ``(mol, opt_mols, mp, cids, bad_ID)`` where ``bad_ID`` is
        ``"error_conf"`` if no conformers could be embedded or ``"OK_conf"``
        otherwise.
    """
    remover = SaltRemover.SaltRemover()
    mol = Chem.MolFromSmiles(smiles)
    mol = remover.StripMol(mol, dontRemoveEverything=True)
    mol = Chem.AddHs(mol)

    p = rdDistGeom.ETKDGv2()
    p.pruneRmsThresh = rmsthresh
    cids = AllChem.EmbedMultipleConfs(mol, nconfs, p)
    try_work_conf = len(cids)

    if try_work_conf == 0:
        print(try_work_conf, "NO__")
        bad_ID = "error_conf"
        opt_mols = 0
        mp = 0
    else:
        print("Number of conformers after pruning:", len(cids))
        mp = AllChem.MMFFGetMoleculeProperties(mol, mmffVariant="MMFF94s")
        opt_mols = AllChem.MMFFOptimizeMoleculeConfs(mol, numThreads=0, mmffVariant="MMFF94s")
        bad_ID = "OK_conf"
        # Second optimisation pass as recommended in the RDKit documentation for ETKDGv2.
        opt_mols = AllChem.MMFFOptimizeMoleculeConfs(mol, numThreads=0, mmffVariant="MMFF94s")

    return mol, opt_mols, mp, cids, bad_ID


def get_energy_conf(mol, mp, cids):
    """Calculate and sort conformer energies using the MMFF force field.

    Parameters
    ----------
    mol : rdkit.Chem.rdchem.Mol
        Molecule with embedded conformers.
    mp : rdkit.Chem.rdForceFieldHelpers.MMFFMolProperties
        MMFF molecule properties object.
    cids : list of int
        Conformer IDs to evaluate.

    Returns
    -------
    tuple
        ``(mol, sorted_res, error)`` where ``sorted_res`` is a list of
        ``(conformer_id, energy)`` tuples sorted by energy (lowest first), and
        ``error`` is ``"OK"`` or ``"ERROR"``.
    """
    res = []
    error = "OK"
    for cid in cids:
        ff = AllChem.MMFFGetMoleculeForceField(mol, mp, confId=cid)
        if ff is None:
            error = "ERROR"
            break
        else:
            e = ff.CalcEnergy()
            res.append((cid, e))

    sorted_res = sorted(res, key=lambda x: x[1])
    return mol, sorted_res, error


def write_SDF(mol, sorted_res, output_pat, mol_n, mol_name, error, error_conf):
    """Write energy-sorted conformers to SDF files.

    Two SDF files are written per molecule: one named by ``mol_name`` and one
    named by the folder index ``mol_n``.

    Parameters
    ----------
    mol : rdkit.Chem.rdchem.Mol
        Molecule with embedded conformers and MMFF properties set.
    sorted_res : list of tuple
        ``(conformer_id, energy)`` pairs, lowest energy first.
    output_pat : str
        Base output directory.
    mol_n : int
        Molecule index (used as the subfolder name).
    mol_name : str
        Molecule identifier (SRN), used as the SDF filename.
    error : str
        ``"ERROR"`` if force-field energy calculation failed, else ``"OK"``.
    error_conf : str
        ``"error_conf"`` if no conformers were embedded, else ``"OK_conf"``.

    Returns
    -------
    str or tuple
        ``"OK"`` on success, or an error message tuple on failure.
    """
    if error == "ERROR":
        message_err = "ERROR IN FOLDER", mol_n, "for mol", mol_name
    elif error_conf == "error_conf":
        message_err = "ERROR IN FOLDER", mol_n, "for mol", mol_name, "BAD ID CONF."
    else:
        out = os.path.join(output_pat, str(mol_n), str(mol_name) + ".sdf")
        out2 = os.path.join(output_pat, str(mol_n), str(mol_n) + ".sdf")
        print(out)
        writeSDF = Chem.SDWriter(out)
        writeSDF2 = Chem.SDWriter(out2)
        message_err = "OK"
        i = 1
        for cid, e in sorted_res:
            mol.SetProp("CID", str(cid))
            mol.SetProp("Energy", str(e))
            name_ID = str(mol_name) + "_" + str(i)
            mol.SetProp("_Name", name_ID)
            writeSDF.write(mol, confId=cid)
            writeSDF2.write(mol, confId=cid)
            i = 1 + i

        writeSDF.close()
        writeSDF2.close()
    return message_err


def sdf_run(folder_mol, list_comp, SMILES, all_str, rmsthresh, nconfs, cluster_number, check):
    """Generate SDF files for a list of compounds under a numbered subfolder.

    For each compound, embeds ETKDGv2 conformers, optimises with MMFF94s,
    sorts by energy, and writes SDF files.  Skips or overwrites existing
    output folders depending on ``check``.

    Parameters
    ----------
    folder_mol : str
        Root output directory.  Conformer files are written under
        ``<folder_mol>/<cluster_number>/<index>/``.
    list_comp : list of str
        SRN identifiers for the compounds to process.
    SMILES : str
        SMILES column name in ``all_str``.
    all_str : pandas.DataFrame
        Full compound DataFrame with at least ``SRN`` and ``SMILES`` columns.
    rmsthresh : float
        RMSD pruning threshold for conformer diversity (0.1 recommended).
    nconfs : int
        Maximum number of conformers to embed per compound.
    cluster_number : int
        Subfolder index under ``folder_mol``.
    check : {"OVERWRITE", "NO OVERWRITE"}
        ``"OVERWRITE"`` removes existing output folders before regenerating.

    Returns
    -------
    str
        Last computed force-field error status (``"OK"`` or ``"ERROR"``).
    """
    folder_mol = os.path.join(folder_mol, str(cluster_number)) + os.sep
    skip = []
    for i in range(0, len(list_comp)):
        subfolder = os.path.join(folder_mol, str(i))
        if not os.path.exists(subfolder):
            os.makedirs(subfolder)
            skip.append("go")
        else:
            if check == "NO OVERWRITE":
                skip.append("stop")
            elif check == "OVERWRITE":
                shutil.rmtree(subfolder)
                os.makedirs(subfolder)
                skip.append("go")

    count = 0
    error_message = []
    for index, cmp in enumerate(list_comp):
        if skip[index] == "go":
            sel_comp = all_str[["SRN", SMILES]][all_str["SRN"] == cmp]
            info_mol = get_info_mol(sel_comp.iloc[0], folder_mol, nconfs, SMILES)
            conf = get_conf_MMFF_opt(info_mol[0], rmsthresh, nconfs)

            if conf[4] == "error_conf":
                print("Conformer Error")
                count = count + 1
                continue
            else:
                al_mol = get_energy_conf(conf[0], conf[2], conf[3])
                message_err = write_SDF(al_mol[0], al_mol[1], info_mol[1], count, info_mol[2], al_mol[2], conf[4])
                count = count + 1
                if message_err != "OK":
                    error_message.append(message_err)

            print("#*#*#*#*#*#*#*#*#*#*#*#*#*#*#*#*#*#*#*#*#*#*#*#*#")
        else:
            print("FOLDER HAVING INDEX:", index, "ALREADY AVAILABLE! PUT OVERWRITE TO REMOVE THE PREVIOUS FILES AND UPDATE THE FOLDER")
            continue

    print(error_message)
    print(al_mol[2])

    return al_mol[2]
